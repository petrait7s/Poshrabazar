// Generates supabase/seed.sql from the demo data in src/data. Run: npm run db:seed:generate
import { writeFileSync } from "node:fs";
import { divisions, upazilas } from "../src/data/locations";
import { categories, products, sellers, offersFor } from "../src/data/catalog";
import { markets, priceRows } from "../src/data/prices";

const q = (s: string | null | undefined) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const kindMap: Record<string, string> = { "কৃষক": "farmer", "খামারি": "farm_owner", "পাইকার": "wholesaler", "আড়তদার": "aratdar", "দোকানদার": "shopkeeper", "কারিগর": "artisan" };
const paisa = (taka: number) => Math.round(taka * 100);
const out: string[] = [];
const w = (s = "") => out.push(s);

w("-- GENERATED by scripts/generate-seed.ts from src/data — do not edit by hand.");
w("-- Demo data only: sellers, prices and stock are illustrative.");
w("begin;");
w();

// geography
let did = 0;
w("insert into divisions (id, name_bn, name_en) values");
w(divisions.map((d, i) => `  (${i + 1}, ${q(d.bn)}, ${q(d.en)})`).join(",\n") + "\non conflict (id) do nothing;");
w();
w("insert into districts (id, division_id, name_bn) values");
w(divisions.flatMap((d, i) => d.districts.map((n) => `  (${++did}, ${i + 1}, ${q(n)})`)).join(",\n") + "\non conflict (id) do nothing;");
w();

// upazilas (launch region only; coordinates intentionally left empty until verified data is loaded)
w("insert into upazilas (district_id, name_bn, name_en)");
w("select d.id, v.name_bn, v.name_en from (values");
w(Object.entries(upazilas).flatMap(([dist, list]) => list.map((u) => `  (${q(dist)}, ${q(u.bn)}, ${q(u.en)})`)).join(",\n"));
w(") as v(district, name_bn, name_en) join districts d on d.name_bn = v.district\non conflict (district_id, name_bn) do nothing;");
w();

// categories & products
w("insert into categories (slug, name_bn, name_en, blurb, sort) values");
w(categories.map((c, i) => `  (${q(c.slug)}, ${q(c.bn)}, ${q(c.en)}, ${q(c.blurb)}, ${i})`).join(",\n") + "\non conflict (slug) do nothing;");
w();
w("insert into products (slug, category_id, name_bn, name_en, unit_bn, description, origin, season, moq_wholesale, famous_district_id)");
w("select v.slug, c.id, v.name_bn, v.name_en, v.unit_bn, v.description, v.origin, v.season, v.moq, fd.id from (values");
w(products.map((p) => `  (${q(p.slug)}, ${q(p.category)}, ${q(p.bn)}, ${q(p.en)}, ${q(p.unit)}, ${q(p.desc)}, ${q(p.origin)}, ${q(p.season ?? null)}, ${p.minWholesale}, ${q(p.famous ?? null)})`).join(",\n"));
w(") as v(slug, cat, name_bn, name_en, unit_bn, description, origin, season, moq, famous) join categories c on c.slug = v.cat left join districts fd on fd.name_bn = v.famous\non conflict (slug) do nothing;");
w();

// sellers
w("insert into sellers (slug, name_bn, name_en, kind, description, district_id, serves_nationwide, verification, since_year)");
w("select v.slug, v.name_bn, v.name_en, v.kind::seller_kind, v.descr, d.id, v.nation, v.ver::verification_status, v.since from (values");
w(sellers.map((s) => `  (${q(s.slug)}, ${q(s.bn)}, ${q(s.en)}, ${q(kindMap[s.kind])}, ${q(s.desc)}, ${q(s.location)}, ${!!s.nationwide || s.kind === "পাইকার" || s.kind === "আড়তদার"}, ${q(s.verified ? "verified" : "pending")}, ${s.since})`).join(",\n"));
w(") as v(slug, name_bn, name_en, kind, descr, district, nation, ver, since) join districts d on d.name_bn = v.district\non conflict (slug) do nothing;");
w();
// every seller delivers to own division
w("insert into seller_coverage (seller_id, division_id)");
w("select s.id, d.division_id from sellers s join districts d on d.id = s.district_id\non conflict do nothing;");
w();

// offers
const rows: string[] = [];
for (const p of products) {
  for (const o of offersFor(p)) {
    rows.push(`  (${q(p.slug)}, ${q(o.sellerSlug)}, ${paisa(o.retail)}, ${paisa(o.wholesale)}, ${o.minWholesale}, ${o.stock}, ${q(o.grade)}, ${q(p.origin)})`);
  }
}
w("insert into offers (product_id, seller_id, retail_paisa, wholesale_paisa, moq, stock_qty, grade, origin, status)");
w("select p.id, s.id, v.r, v.w, v.moq, v.stock, v.grade, v.origin, 'active' from (values");
w(rows.join(",\n"));
w(") as v(pslug, sslug, r, w, moq, stock, grade, origin) join products p on p.slug = v.pslug join sellers s on s.slug = v.sslug\non conflict (product_id, seller_id) do nothing;");
w();

// markets & 7 days of prices (relative to today so charts always look current)
w("insert into markets (slug, name_bn, district_id)");
w("select v.slug, v.name_bn, d.id from (values");
w(markets.map((m) => `  (${q(m.slug)}, ${q(m.bn)}, ${q(m.city)})`).join(",\n"));
w(") as v(slug, name_bn, city) join districts d on d.name_bn = v.city\non conflict (slug) do nothing;");
w();
const pr: string[] = [];
for (const r of priceRows) for (const m of markets) r.trend.forEach((t, i) => {
  const retail = paisa(Math.round(t * m.f * 1.04)), whole = paisa(Math.round(t * m.f * 0.9));
  pr.push(`  (${q(r.slug)}, ${q(m.slug)}, ${6 - i}, ${retail}, ${whole})`);
});
w("insert into market_prices (product_id, market_id, price_date, retail_paisa, wholesale_paisa)");
w("select p.id, m.id, current_date - v.ago, v.r, v.w from (values");
w(pr.join(",\n"));
w(") as v(pslug, mslug, ago, r, w) join products p on p.slug = v.pslug join markets m on m.slug = v.mslug\non conflict (product_id, market_id, price_date) do nothing;");
w();

w("commit;");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n") + "\n");
console.log(`seed.sql: ${products.length} products, ${sellers.length} sellers, ${rows.length} offers, ${pr.length} price rows`);
